import { $, $$, expect, click, heading, audit } from './helpers';
describe('real native persistence', () => {
  it('creates an Arabic deck and multilingual variants using the real SQLite backend', async () => {
    await heading('مجموعاتي');
    await audit('native-library');
    await click('إنشاء مجموعة');
    await $('dialog input').setValue('اختبار أصلي');
    await click('إنشاء');
    await click('اختبار أصلي');
    await heading('اختبار أصلي');
    await click('إنشاء بطاقة');
    const fields = await $$('dialog textarea');
    await fields[0].setValue('سؤال أصلي English <h1>نص</h1>');
    await fields[1].setValue('إجابة 日本語');
    await fields[2].setValue('ملاحظة أصلية');
    await click('إضافة صيغة بديلة');
    const variants = await $$('dialog textarea');
    await variants[3].setValue('صيغة بديلة 日本語');
    await variants[4].setValue('بديل English');
    await audit('native-card-editor');
    await click('حفظ البطاقة');
    await expect($('dialog')).not.toExist();
    await click('استيراد بطاقات JSON');
    await click('اختيار ملف JSON');
    await click('فحص JSON');
    await expect($('h3=معاينة البطاقات')).toBeDisplayed();
    await audit('native-import-preview');
    await click('استيراد البطاقات المحددة');
    await expect($('dialog')).not.toExist();
    await click('استيراد بطاقات JSON');
    await click('اختيار ملف JSON');
    await click('فحص JSON');
    await expect($('button=استيراد البطاقات المحددة')).toBeDisabled();
    await audit('native-duplicate-preview');
    await click('إلغاء');
    await click('العودة إلى المجموعات');
    await heading('مجموعاتي');
    await expect($('button=اختبار أصلي')).toBeDisplayed();
  });
});
