import { browser, $, expect, click, heading, audit } from './helpers';
describe('native restart and live review', () => {
  it('reopens persisted cards, filters due work, adds an arriving card, rotates its form and undoes the summary', async () => {
    await heading('مجموعاتي');
    await expect($('button=اختبار أصلي')).toBeDisplayed();
    await click('الإعدادات');
    await $('summary=إعدادات متقدمة').click();
    await $('input[name="minIntervalSeconds"]').setValue('10');
    await click('حفظ الإعدادات');
    await expect($('p=حُفظت الإعدادات.')).toBeDisplayed();
    await click('المجموعات');
    await click('اختبار أصلي');
    await click('بدء المراجعة');
    await heading('السؤال');
    await expect($('input[value="all"]')).toBeChecked();
    const first = await $('.question-text').getText();
    await click('عرض الإجابة');
    await expect($('h2=الإجابة')).toBeFocused();
    await expect($('.rating-again')).toHaveAttribute('aria-describedby');
    await audit('native-revealed');
    await $('.rating-again').click();
    const parked = await $('.question-text').getText();
    expect(parked).not.toEqual(first);
    await $('input[value="previouslyReviewed"]').click();
    await heading('لا توجد بطاقات مطابقة الآن');
    await audit('native-empty-filter');
    await $('input[value="new"]').click();
    await heading('السؤال');
    await expect($('.question-text')).toHaveText(parked);
    await browser.pause(11_000);
    await expect($('.question-text')).toHaveText(parked);
    await $('input[value="all"]').click();
    await click('عرض الإجابة');
    await $('.rating-easy').click();
    await heading('السؤال');
    const rotated = await $('.question-text').getText();
    expect(rotated).not.toEqual(first);
    expect(rotated).not.toEqual(parked);
    await click('عرض الإجابة');
    await $('.rating-easy').click();
    await heading('ملخص الجلسة');
    await audit('native-summary');
    await click('التراجع عن آخر تقييم');
    await expect($('.question-text')).toHaveText(rotated);
    await expect($('h2=الإجابة')).toBeFocused();
    await $('.rating-easy').click();
    await heading('ملخص الجلسة');
    await click('العودة إلى المجموعة');
    await click('العودة إلى المجموعات');
  });
});
