import { browser, $, $$, expect, click, heading, audit, root, containing } from './helpers';
import { copyFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
describe('real offline editing, profiles and portable restore', () => {
  it('edits/deletes a card, links/detaches a profile and enforces the training gate without network', async () => {
    await heading('مجموعاتي');
    await click('اختبار أصلي');
    await click('إنشاء بطاقة');
    const fields = await $$('dialog textarea');
    await fields[0].setValue('مؤقت');
    await fields[1].setValue('answer');
    await click('حفظ البطاقة');
    await $('summary=البطاقات').click();
    await expect($('p=مؤقت')).toBeDisplayed();
    const row = await containing('li.collection', 'مؤقت');
    await row.$('button:not(.danger)').click();
    await $('dialog textarea').setValue('بطاقة معدلة');
    await click('حفظ البطاقة');
    await expect($('p=بطاقة معدلة')).toBeDisplayed();
    const edited = await containing('li.collection', 'بطاقة معدلة');
    await edited.$('button.danger').click();
    await click('حذف البطاقة نهائيًا');
    await expect($('p=بطاقة معدلة')).not.toExist();
    await click('نماذج التحسين');
    await click('إنشاء نموذج تحسين');
    await $('dialog input').setValue('تجميعي');
    await click('إنشاء النموذج');
    await $('summary=تجميعي').click();
    const profile = await containing('details.disclosure', 'تجميعي');
    // The embedded driver does not implement a native select's default action.
    // Dispatch the real DOM change; every profile operation still goes to Rust.
    await browser.execute(() => {
      const select = document.querySelector<HTMLSelectElement>('details[open] select')!;
      select.value = select.options[1].value;
      select.dispatchEvent(new Event('change', { bubbles: true }));
    });
    await click('ربط المجموعة بالنموذج');
    await click('تأكيد الربط');
    await profile.$('button=فصل المجموعة').waitForExist();
    await profile.$('summary=تحسين النموذج').click();
    await expect(profile.$('button=بدء التحسين')).toBeDisabled();
    await audit('native-training-gate');
    await profile.$('button=فصل المجموعة').click();
    await click('تأكيد الفصل');
    await click('المجموعات');
  });
  it('exports real data, verifies the payload, restores after deletion, then tolerates an offline updater check', async () => {
    await click('الإعدادات');
    await $('summary=النسخ الاحتياطي والاستعادة').click();
    await click('تصدير جميع البيانات');
    await expect($('p=اكتمل تصدير النسخة الاحتياطية.')).toBeDisplayed();
    const path = await $('.result p[dir="auto"]').getText();
    const backup = JSON.parse(readFileSync(path, 'utf8'));
    expect(backup.formatVersion).toBe(2);
    copyFileSync(path, resolve(root, 'restore.json'));
    await click('المجموعات');
    await $('button[aria-label="حذف اختبار أصلي"]').click();
    await click('حذف المجموعة نهائيًا');
    await expect($('button=اختبار أصلي')).not.toExist();
    await click('الإعدادات');
    await $('summary=النسخ الاحتياطي والاستعادة').click();
    await click('اختيار نسخة للاستعادة');
    await expect($('h2=معاينة الاستعادة')).toBeDisplayed();
    await audit('native-restore-preview');
    await $('dialog input[type="checkbox"]').click();
    await click('استعادة النسخة واستبدال المكتبة');
    await heading('مجموعاتي');
    await expect($('button=اختبار أصلي')).toBeDisplayed();
    await expect($('p=تمت استعادة النسخة الاحتياطية.')).toBeDisplayed();
    await audit('native-restored');
    await click('الإعدادات');
    await $('summary=تحديث التطبيق').click();
    await click('التحقق من وجود تحديث');
    await expect($('[role="alert"]')).toBeDisplayed();
    await click('المجموعات');
    await click('اختبار أصلي');
    await heading('اختبار أصلي');
  });
});
